-- Review & Flashcards
-- Flashcard 1: What does the SELECT statement do in SQL?
-- Answer: The SELECT statement is used to select data from a database.

-- Flashcard 2: How do you use the WHERE clause in SQL?
-- Answer: The WHERE clause is used to filter records based on specified conditions.

-- Flashcard 3: What is the purpose of the ORDER BY clause?
-- Answer: The ORDER BY clause is used to sort the result-set in ascending or descending order.

-- Flashcard 4: Explain the DISTINCT keyword in SQL.
-- Answer: The DISTINCT keyword is used to return only distinct (different) values.

-- Flashcard 5: How can you limit the number of records returned by a query?
-- Answer: You can use the LIMIT keyword to limit the number of records returned by a query.

-- Flashcard 6: What is the difference between LIKE and ILIKE in SQL?
-- Answer: LIKE is case-sensitive, while ILIKE is case-insensitive when matching patterns.

-- Flashcard 7: How do you implement pagination in SQL?
-- Answer: Use the LIMIT and OFFSET keywords to implement pagination.

-- Flashcard 8: What does the BETWEEN operator do in SQL?
-- Answer: The BETWEEN operator selects values within a given range.

-- Flashcard 9: How do you check for NULL values in SQL?
-- Answer: Use the IS NULL condition to check for NULL values.

-- Flashcard 10: What is an alias in SQL?
-- Answer: An alias is a temporary name given to a table or column to make the query more readable.